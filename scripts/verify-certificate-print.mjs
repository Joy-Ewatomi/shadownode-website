import assert from "node:assert/strict"
import { readFileSync } from "node:fs"

const component = readFileSync("components/training/TrainingCertificate.tsx", "utf8")
const page = readFileSync("app/dashboard/training/[id]/certificate/page.tsx", "utf8")
const list = readFileSync("app/dashboard/client/certificates/ClientCertificateList.tsx", "utf8")
const api = readFileSync("app/api/training/[id]/certificate/route.ts", "utf8")

assert.match(component, /@page\s*\{[\s\S]*size: A4 landscape;[\s\S]*margin: 8mm;/)
assert.match(component, /width: 100% !important;/)
assert.match(component, /height: auto !important;/)
assert.match(component, /max-width: 274mm !important;/)
assert.match(component, /max-height: 194mm !important;/)
assert.match(component, /aspect-ratio: 297 \/ 210 !important;/)
assert.match(component, /transform: translateX\(-50%\) !important;/)
assert.doesNotMatch(component, /(?:width|min-width): 281mm !important;/)
const letterPrintableWidthMm = 279.4 - 16
const configuredMaximumWidthMm = 274
assert.ok(letterPrintableWidthMm < configuredMaximumWidthMm, "Letter must select width: 100% instead of the A4 maximum")
assert.ok(letterPrintableWidthMm / (297 / 210) < 215.9 - 16, "Letter-scaled certificate must fit printable height")
assert.match(component, /body\.printing-training-certificate \*[\s\S]*visibility: hidden !important;/)
assert.match(component, /#training-certificate,[\s\S]*#training-certificate \*[\s\S]*visibility: visible !important;/)
assert.match(component, /height: 0 !important;[\s\S]*position: fixed !important;/)
assert.match(component, /print-color-adjust: exact !important;/)
assert.match(component, /document\.fonts\?\.ready/)
assert.match(component, /image\.decode\(\)/)
assert.match(component, /automaticPrintStarted\.has\(cert\.id\)/)
assert.match(component, /automaticPrintStarted\.add\(cert\.id\)/)
assert.match(component, /certificateVisualReady/)
assert.match(page, /ensureAccess\(\s*id,\s*user,/)
assert.match(page, /\(selectedCertificateId \|\| selectedParticipantId\)[\s\S]*!rawCertificate[\s\S]*return notFound\(\)/)
assert.match(page, /WHERE training_engagement_id = \$1[\s\S]*OR id = \$2::uuid/)
assert.doesNotMatch(component, /Joy Ewatomi/)
assert.doesNotMatch(component, /trainer_name:\s*"ShadowNode Training Facilitator"/)
assert.doesNotMatch(list, /download=\{`\$\{certificate\.certificate_number\}\.html`\}/)
assert.match(list, /certificate\.pdf_url[\s\S]*Download certificate/)
assert.match(api, /pdf_url/)
assert.match(component, /Print \/ Save as PDF/)
console.log("Certificate print checks passed (28 assertions).")
