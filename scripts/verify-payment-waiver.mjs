import assert from "node:assert/strict"
import { readFileSync } from "node:fs"

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8")
const service = read("lib/services/payment-waiver-service.ts")
const route = read("app/api/admin/requests/[id]/waive-payment/route.ts")
const control = read("components/requests/PaymentWaiverControl.tsx")
const reviewPage = read("app/dashboard/super-administrator/requests/[id]/page.tsx")
const providers = read("app/api/client/payments/providers/route.ts")
const paymentPage = read("app/dashboard/client/payments/[id]/page.tsx")
const trainingAccess = read("lib/services/training-operations-service.ts")

assert.match(service, /isSuperAdministratorRole\(input\.actorRole\)/)
assert.match(service, /status !== "awaiting_payment"/)
assert.match(service, /!request\.accepted_quote_version_id/)
assert.match(service, /hasCase === hasTraining/)
assert.match(service, /SELECT 1 FROM payments WHERE request_id = \$1 LIMIT 1 FOR UPDATE/)
assert.match(service, /Payment cannot be waived after a payment attempt has started/)
assert.match(service, /payment_status = 'waived'/)
assert.match(service, /to: "awaiting_assignment"/)
assert.match(service, /preferred_start_date > CURRENT_DATE[\s\S]*THEN 'scheduled' ELSE 'active'/)
assert.match(service, /"payment_waived"/)
assert.match(service, /strict: true/)
assert.match(service, /Payment requirement waived/)
assert.doesNotMatch(service, /INSERT INTO payments/)
assert.doesNotMatch(service, /payment_status = 'paid'/)

assert.match(route, /isSameOriginMutation\(request\)/)
assert.match(route, /getCurrentUser\(\)/)
assert.match(route, /actorUserId: user\.id/)
assert.match(route, /actorRole: user\.role/)
assert.match(route, /Cache-Control": "private, no-store"/)
assert.doesNotMatch(route, /body\?\.(role|userId|user_id)/)

assert.match(reviewPage, /isSuperAdministratorRole\(user\.role\)/)
assert.match(reviewPage, /<PaymentWaiverControl/)
assert.match(control, /window\.confirm/)
assert.match(control, /acknowledged/)
assert.match(control, /method: "POST"/)
assert.match(control, /No paid transaction will be created/)

assert.match(providers, /const isWaived = targetPaymentStatus === "waived"/)
assert.match(providers, /&& !isWaived/)
assert.match(paymentPage, /const isSettled = isPaid \|\| isWaived/)
assert.match(paymentPage, /Payment requirement waived/)
assert.match(paymentPage, /Payment Waived/)
assert.match(trainingAccess, /\["paid", "waived"\]\.includes\(engagement\.payment_status/)

console.log("Payment-waiver verifier passed.")
