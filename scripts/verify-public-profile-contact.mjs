import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8")
const settings = read("app/api/admin/public-profile/route.ts")
const assets = read("app/api/admin/public-profile/[asset]/route.ts")
const contact = read("app/api/public/contact/route.ts")
const profile = read("lib/public-site-profile.ts")
const homepage = read("app/page.tsx")
const schema = read("scripts/schema.md")

assert.match(settings, /isSuperAdministratorRole\(user\.role\)/)
assert.match(settings, /isSameOriginMutation\(request\)/)
assert.match(settings, /safePublicUrl\(body\?\.linkedin_url, "www\.linkedin\.com"\)/)
assert.match(assets, /isSuperAdministratorRole\(user\.role\)/)
assert.match(assets, /application\/pdf/)
assert.match(assets, /%PDF-/)
assert.match(assets, /limitInputPixels/)
assert.match(profile, /has_portrait: Boolean\(row\.portrait_path\)/)
assert.doesNotMatch(profile, /portrait_path: row\.portrait_path/)
assert.match(contact, /isSameOriginMutation\(request\)/)
assert.match(contact, /pg_advisory_xact_lock/)
assert.ok(contact.indexOf("INSERT INTO contact_inquiries") < contact.indexOf("sendEmail({"), "Enquiry must persist before email delivery")
assert.match(contact, /email_delivery_status='failed'/)
assert.match(homepage, /\/api\/public\/site-profile\/portrait/)
assert.match(homepage, /\/api\/public\/site-profile\/sample-report/)
assert.match(homepage, /BOOK AN INTRO CALL/)
assert.match(schema, /CREATE TABLE public\.public_site_profile/)
assert.match(schema, /CREATE TABLE public\.contact_inquiries/)
assert.match(schema, /'public-site',[\s\S]*'public-site',[\s\S]*false/)
console.log("Public profile and contact verifier passed.")
