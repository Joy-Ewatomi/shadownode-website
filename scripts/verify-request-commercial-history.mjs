import assert from "node:assert/strict"
import { readFileSync } from "node:fs"

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8")
const migration = read("scripts/request-commercial-history.sql")
const history = read("lib/services/commercial-history-service.ts")
const initialize = read("app/api/client/payments/initialize/route.ts")
const payment = read("lib/services/paystack-payment-service.ts")
const callback = read("app/api/client/payments/callback/route.ts")
const requestApi = read("app/api/client/requests/[id]/route.ts")
const requestPage = read("app/dashboard/client/requests/[id]/page.tsx")
const requestListApi = read("app/api/client/requests/route.ts")
const requestListPage = read("app/dashboard/client/requests/page.tsx")
const adminRequestPage = read("app/dashboard/requests/[id]/page.tsx")
const paymentPage = read("app/dashboard/client/payments/[id]/page.tsx")
const caseConversion = read("lib/services/case-conversion-service.ts")
const trainingConversion = read("lib/services/training-engagement-conversion-service.ts")

assert.match(migration, /accepted_quote_version_id uuid REFERENCES quote_versions/)
assert.match(migration, /quote_version_id uuid REFERENCES quote_versions/)
assert.match(migration, /uq_successful_payment_per_quote/)
assert.match(migration, /Historical backfill is intentionally not automatic/)
assert.match(history, /ORDER BY version_number ASC/)
