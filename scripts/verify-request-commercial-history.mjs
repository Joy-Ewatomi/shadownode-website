assert.doesNotMatch(history, /reasoning|administrator_recommendation|owner_decision_notes/)
assert.match(initialize, /q\.id = r\.accepted_quote_version_id/)
assert.match(initialize, /quote_version_id, provider_reference/)
assert.doesNotMatch(initialize, /UPDATE payments p[\s\S]*FROM existing/)
assert.match(payment, /Payment is not linked to the accepted quotation/)
assert.match(payment, /payment\.accepted_quote_version_id !== payment\.quote_version_id/)
assert.match(payment, /Number\(payment\.amount\) !== Number\(payment\.quote_price\)/)
assert.match(payment, /recordPaymentReviewFailure\(payment\.id, payment\.request_id, "quote_mismatch"\)/)
assert.match(payment, /FOR UPDATE/)
assert.match(payment, /verified_at = NOW\(\)/)
assert.match(payment, /UPDATE quote_versions SET status = 'paid'/)
assert.match(caseConversion, /markAcceptedQuoteVersion/)
assert.match(trainingConversion, /markAcceptedQuoteVersion/)
assert.match(requestApi, /user_id = \$2/)
assert.match(requestApi, /getCommercialHistory\(id\)/)
